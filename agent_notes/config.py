def memory_dir_for_backend(backend: str, custom_path: str = "") -> Optional[Path]:
    """Return the root memory directory for the given backend and optional custom path."""
    if backend == "local":
        return Path(custom_path).expanduser() if custom_path else MEMORY_DIR
    # obsidian is project-scoped
    if custom_path:
        root = Path(custom_path).expanduser()
    elif backend == "obsidian":
        root = Path.home() / DEFAULT_VAULT_DIR / DEFAULT_VAULT_NAME / Obsidian.SUBFOLDER
    else:
        return MEMORY_DIR
    project = Path.cwd().name
    return root / project

def get_version() -> str:
    """Read version from VERSION file."""
    try:
        return VERSION_FILE.read_text().strip()
    except FileNotFoundError:
        return "unknown"

def find_skill_dirs() -> list[Path]:
    """Find all skill directories (containing SKILL.md).
    
    DEPRECATED: Use agent_notes.registries.default_skill_registry() instead.
    This is kept as a shim for backward compatibility.
    """
    # For backward compatibility, first try the original filesystem-based implementation
    # This ensures tests that mock SKILLS_DIR still work
    if SKILLS_DIR.is_dir():
        return sorted(d for d in SKILLS_DIR.iterdir() if d.is_dir() and (d / "SKILL.md").exists())
    return []


def is_reserved_skill_name(name: str) -> bool:
    """Claude Code owns ~/.claude/skills/synced (its mirror of claude.ai skills) and
    ~/.claude/skills/.trash (removed personal skills); a shipped skill must never
    claim either name."""
    return name.casefold() == "synced" or name.startswith(".")


def is_reserved_skill_entry(path) -> bool:
    """True when *path* is a reserved name (synced, .trash, a dot name) sitting directly in a
    directory called `skills`: Claude Code's own place, never ours to place over or move.
    Only the entry and its parent are looked at, so a project or home that merely has
    `skills` or a dot-directory somewhere above the install is not caught."""
    path = Path(path)
    return path.parent.name.casefold() == "skills" and is_reserved_skill_name(path.name)


def placeable_skill_dirs(dist_skills_dir) -> list[Path]:
    """The skill directories of *dist_skills_dir* that may be placed, sorted: the reserved
    names (see is_reserved_skill_name) never are."""
    dist_skills_dir = Path(dist_skills_dir)
    if not dist_skills_dir.is_dir():
        return []
    return sorted(d for d in dist_skills_dir.iterdir()
                  if d.is_dir() and not is_reserved_skill_name(d.name))


# === Registry-driven path helpers ===

def dist_dir_for(backend) -> Path:
    """Return dist directory path for a backend."""
    return DIST_DIR / backend.name


def global_template_path(backend) -> Optional[Path]:
    """Return path to global template source file for backend, or None if no template."""
    if not backend.global_template:
        return None
    return DATA_DIR / backend.global_template


def global_output_path(backend) -> Optional[Path]:
    """Return path where global template should be generated in dist, or None if no template."""
    if not backend.global_template or not backend.layout.get("config"):
        return None
    return dist_dir_for(backend) / backend.layout["config"]


# === Backward compatibility constants ===
# Hardcoded fallbacks match the shipped YAMLs and protect against circular
# imports if this module is ever imported very early in the load sequence.
_FALLBACKS = {
    'claude':   {'home': Path.home() / ".claude",               'template': "global-claude.md",   'dist': "claude"},
    'opencode': {'home': Path.home() / ".config" / "opencode",  'template': "global-opencode.md", 'dist': "opencode"},
    'copilot':  {'home': Path.home() / ".github",               'template': "global-copilot.md",  'dist': "github"},
}


def _backend_home(name: str) -> Path:
    try:
        from .registries.cli_registry import default_registry
        return default_registry().get(name).global_home
    except (ImportError, KeyError):
        return _FALLBACKS[name]['home']


def _backend_dist(name: str) -> Path:
    try:
        from .registries.cli_registry import default_registry
        return dist_dir_for(default_registry().get(name))
    except (ImportError, KeyError):
        return DIST_DIR / _FALLBACKS[name]['dist']


def _backend_template(name: str) -> Path:
    try:
        from .registries.cli_registry import default_registry
        return global_template_path(default_registry().get(name))
    except (ImportError, KeyError):
        return DATA_DIR / _FALLBACKS[name]['template']


